# Atribui o codigo numerico do funcionario
codigo = 105

# armazena o nome completo do funcionario
nome = "jose santana"

#define o salario como numero decimal
salario = 1650.00

# indica se o funcionario esta ativo no sistema
ativo = True

# exibe o codigo usando formataçao %d(inteiro)
print("codigo: %d" % codigo)

#exibe o nome usando %s (string)
print("nome: %s" % nome)

#exibe o salario com duas casas decimais usando %.2f(float)
print("salario: %.2f" % salario)

#exibe o valor booleano usando %r (representaçao literal)
print("ativo: %r" % ativo)